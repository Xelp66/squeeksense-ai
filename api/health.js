'use strict';
const {reply,error,getAPI}=require('./_lib');
module.exports=async function(req,res){
 if(req.method!=='GET')return error(res,'Method not allowed',405);
 let status,serverError=null;
 try{status=await getAPI('/status')}catch(e){serverError=e}
 const isBlocked=serverError?.code==='UPSTREAM_CHALLENGE';
 if(!status){
   return reply(res,200,{checkedAt:new Date().toISOString(),apiReachable:false,
     upstream:{state:isBlocked?'server-challenged':'unreachable',errorCode:serverError?.code||'UNKNOWN',httpStatus:serverError?.status||null,
       explanation:isBlocked?'Upstream Cloudflare presents an access challenge to Vercel server requests. This does not establish whether the hamster is online.':'Upstream Squeekchain telemetry could not be fetched from this server.',
       browserDirectRecommended:true},
     live:{state:'api-error',connected:false,readingFresh:false,lastObservedAt:null,lastReceivedAt:null,provenance:null,
       rpm:null,remark:'Server cannot confirm wheel state. Use the browser-direct API health panel.'},
     history:{available:false,days:0},runs:{available:false,count:0}});
 }
 const m=status.measurement||null;
 // Compare timestamps generated by the API, never with a user's unsynchronized clock.
 const ageMs=m&&Date.parse(status.generatedAt)&&Date.parse(m.receivedAt||m.observedAt)?
   Math.max(0,Date.parse(status.generatedAt)-Date.parse(m.receivedAt||m.observedAt)):Infinity;
 const fresh=Boolean(m&&m.freshness==='online'&&ageMs<=Math.max(120000,Number(m.staleAfterSeconds||120)*1000));
 const state=!m?'no-measurement':!fresh?'stale':m.coreStatus==='ACTIVE'?'running':m.coreStatus==='IDLE'?'still':'hardware-alert';
 const [history,runs]=await Promise.allSettled([
   getAPI('/measurement/stats?range=7d'),
   getAPI('/measurement/runs?limit=25')
 ]);
 const h=history.status==='fulfilled'?history.value:null;
 const r=runs.status==='fulfilled'?runs.value:null;
 return reply(res,200,{checkedAt:new Date().toISOString(),apiReachable:true,
   upstream:{state:'available',errorCode:null,browserDirectRecommended:false},
   live:{state,connected:true,readingFresh:fresh,lastObservedAt:m?.observedAt||null,lastReceivedAt:m?.receivedAt||null,
     freshness:m?.freshness||null,deviceStatus:m?.coreStatus||null,provenance:m?.provenance||null,
     rpm:fresh&&Number.isFinite(m?.rpmMilli)?m.rpmMilli/1000:null,
     distanceMeters:fresh&&Number.isFinite(m?.distanceMm)?m.distanceMm/1000:null,
     remark:!m?'No device reading':fresh&&m.coreStatus==='ACTIVE'?'Recorded wheel movement':fresh&&m.coreStatus==='IDLE'?'Wheel still; not proof of sleep':'Device reading is stale or unavailable'},
   history:{available:Boolean(h?.activity?.days),days:h?.activity?.days?.length||0},
   runs:{available:Boolean(r&&Array.isArray(r.items)),count:r?.items?.length||0,
     freshness:r?.freshness||null,coverageThroughAt:r?.coverageThroughAt||null}
 });
};